let SEMESTER      = 'fall';          // 'spring' | 'summer' | 'fall'
let COURSES       = FALL_COURSES;
let SCHEDULE_DATA = FALL_SCHEDULE;
let QNA_SCHEDULE  = FALL_QNA;
let STUDENTS      = FALL_STUDENTS;

function applySemester(sem) {
  SEMESTER = (sem === 'summer' || sem === 'fall' || sem === 'spring') ? sem : 'fall';
  if (SEMESTER === 'summer') {
    COURSES       = SUMMER_COURSES;
    SCHEDULE_DATA = SUMMER_OFFLINE;   // 토요일 오프라인 + 해외글로벌세미나 + 중간/기말고사
    QNA_SCHEDULE  = SUMMER_QNA;
    STUDENTS      = SUMMER_STUDENTS;
  } else if (SEMESTER === 'fall') {
    COURSES       = FALL_COURSES;
    SCHEDULE_DATA = FALL_SCHEDULE;    // 토요일 오프라인 + 중간/기말고사
    QNA_SCHEDULE  = FALL_QNA;
    STUDENTS      = FALL_STUDENTS;
  } else {
    COURSES       = SPRING_COURSES;
    SCHEDULE_DATA = SPRING_SCHEDULE;
    QNA_SCHEDULE  = SPRING_QNA;
    STUDENTS      = SPRING_STUDENTS;
  }
  return SEMESTER;
}

// ============================================================
// 유틸리티 함수
// ============================================================
function getAllDates() {
  return [...new Set(SCHEDULE_DATA.map(s => s.date))].sort();
}
function getDatesByMonth() {
  const dates = getAllDates();
  const grouped = {};
  dates.forEach(d => {
    const month = d.substring(0, 7);
    if (!grouped[month]) grouped[month] = [];
    grouped[month].push(d);
  });
  return grouped;
}
